"""Replace these ports when connecting real services; graph code stays unchanged."""

from typing import Literal, Protocol

from .schemas import Brief, Candidate, Plan, Review, State


class ModelClient(Protocol):
    def risk(self, text: str) -> Literal["pass", "high", "uncertain"]: ...
    def companion(self, text: str) -> str: ...
    def plan(self, state: State) -> Plan: ...
    def review(self, state: State, candidate: Candidate) -> Review: ...


class ImageBackend(Protocol):
    def generate(self, brief: Brief, *, operation_id: str, seed: int) -> Candidate: ...
    def retrieve(self, brief: Brief) -> Candidate | None: ...

